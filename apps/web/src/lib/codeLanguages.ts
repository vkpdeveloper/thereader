/** "TypeScript", "C++", "Shell"; unknown ids are capitalized. */
export function languageLabel(language: string): string {
  const id = language.trim().toLowerCase();
  return labels[id] ?? labels[aliases[id] ?? ''] ?? id.charAt(0).toUpperCase() + id.slice(1);
}
