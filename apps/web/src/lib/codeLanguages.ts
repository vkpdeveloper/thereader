export type Grammar = (typeof grammars)[number];

const known = new Set<string>(grammars);

/** The highlight.js grammar for a language id, or null when none fits. */
export function grammarFor(language: string): Grammar | null {
  const id = language.trim().toLowerCase();
  const name = aliases[id] ?? id;
  return known.has(name) ? (name as Grammar) : null;
}

